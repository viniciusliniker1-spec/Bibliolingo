-- Phase 3.2: durable, user-owned adaptive recommendation preferences.
-- The mastery profile itself remains derived from answer/review evidence, avoiding stale duplicated scores.

create table if not exists public.adaptive_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  ignored_recommendation_ids text[] not null default '{}',
  recent_recommendation_ids text[] not null default '{}',
  updated_at timestamptz not null default now()
);

create table if not exists public.adaptive_preference_events (
  server_sequence bigint generated by default as identity primary key,
  event_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id uuid not null,
  platform text not null check (platform in ('web', 'android', 'ios')),
  operation text not null check (operation in ('dismiss', 'record')),
  recommendation_id text not null check (char_length(recommendation_id) between 1 and 200),
  created_at timestamptz not null default now()
);

create index if not exists adaptive_preference_events_user_sequence
  on public.adaptive_preference_events(user_id, server_sequence desc);

alter table public.adaptive_preferences enable row level security;
alter table public.adaptive_preference_events enable row level security;

drop policy if exists "adaptive_preferences_select_own" on public.adaptive_preferences;
create policy "adaptive_preferences_select_own" on public.adaptive_preferences
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "adaptive_events_select_own" on public.adaptive_preference_events;
create policy "adaptive_events_select_own" on public.adaptive_preference_events
  for select to authenticated using ((select auth.uid()) = user_id);

create or replace function public.submit_adaptive_preference_event(
  p_event_id uuid,
  p_device_id uuid,
  p_platform text,
  p_payload jsonb
)
returns table(server_sequence bigint, accepted boolean, total_xp integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_operation text := p_payload->>'operation';
  v_recommendation_id text := p_payload->>'recommendation_id';
  v_sequence bigint;
  v_ignored text[];
  v_recent text[];
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if p_platform not in ('web', 'android', 'ios') then raise exception 'Invalid platform'; end if;
  if v_operation not in ('dismiss', 'record') then raise exception 'Invalid operation'; end if;
  if v_recommendation_id is null or char_length(v_recommendation_id) not between 1 and 200 then
    raise exception 'Invalid recommendation';
  end if;

  insert into public.adaptive_preference_events(event_id,user_id,device_id,platform,operation,recommendation_id)
  values (p_event_id,v_user_id,p_device_id,p_platform,v_operation,v_recommendation_id)
  on conflict (event_id) do nothing
  returning adaptive_preference_events.server_sequence into v_sequence;

  if v_sequence is null then
    select e.server_sequence into v_sequence
    from public.adaptive_preference_events e
    where e.event_id=p_event_id and e.user_id=v_user_id;
    return query select v_sequence,false,coalesce((select s.total_xp from public.user_stats s where s.user_id=v_user_id),0);
    return;
  end if;

  insert into public.adaptive_preferences(user_id) values(v_user_id)
  on conflict (user_id) do nothing;

  select ignored_recommendation_ids,recent_recommendation_ids
    into v_ignored,v_recent
  from public.adaptive_preferences where user_id=v_user_id for update;

  if v_operation='dismiss' then
    v_ignored := array_append(array_remove(v_ignored,v_recommendation_id),v_recommendation_id);
    if cardinality(v_ignored)>100 then v_ignored:=v_ignored[(cardinality(v_ignored)-99):cardinality(v_ignored)]; end if;
  else
    v_recent := array_append(array_remove(v_recent,v_recommendation_id),v_recommendation_id);
    if cardinality(v_recent)>20 then v_recent:=v_recent[(cardinality(v_recent)-19):cardinality(v_recent)]; end if;
  end if;

  update public.adaptive_preferences
  set ignored_recommendation_ids=v_ignored,recent_recommendation_ids=v_recent,updated_at=now()
  where user_id=v_user_id;

  return query select v_sequence,true,coalesce((select s.total_xp from public.user_stats s where s.user_id=v_user_id),0);
end;
$$;

revoke all on function public.submit_adaptive_preference_event(uuid,uuid,text,jsonb) from public;
grant execute on function public.submit_adaptive_preference_event(uuid,uuid,text,jsonb) to authenticated;
