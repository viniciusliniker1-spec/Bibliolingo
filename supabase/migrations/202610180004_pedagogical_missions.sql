-- Phase 3.4: immutable, idempotent pedagogical mission events.
create table if not exists public.mission_events (
 server_sequence bigint generated by default as identity primary key,
 event_id text not null,
 user_id uuid not null references auth.users(id) on delete cascade,
 device_id uuid not null,
 platform text not null check(platform in ('web','android','ios')),
 event_kind text not null check(event_kind in ('assignment','lifecycle')),
 payload jsonb not null,
 created_at timestamptz not null default now(),
 unique(user_id,event_id)
);
create index if not exists mission_events_user_sequence on public.mission_events(user_id,server_sequence);
alter table public.mission_events enable row level security;
drop policy if exists "mission_events_select_own" on public.mission_events;
create policy "mission_events_select_own" on public.mission_events for select to authenticated using((select auth.uid())=user_id);

create or replace function public.submit_mission_event(p_event_id uuid,p_device_id uuid,p_platform text,p_payload jsonb)
returns table(server_sequence bigint,accepted boolean,total_xp integer)
language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid();v_kind text:=p_payload->>'kind';v_value jsonb:=p_payload->'value';v_seq bigint;
begin
 if v_user is null then raise exception 'Authentication required';end if;
 if p_platform not in ('web','android','ios') then raise exception 'Invalid platform';end if;
 if v_kind not in ('assignment','lifecycle') or jsonb_typeof(v_value)<>'object' then raise exception 'Invalid mission event';end if;
 if length(v_value::text)>20000 then raise exception 'Mission event too large';end if;
 if coalesce(v_value->>'id','')='' or char_length(v_value->>'id')>300 then raise exception 'Invalid identifier';end if;
 if v_kind='assignment' then
  if v_value->>'cadence' not in ('daily','weekly','thematic','open') or v_value->>'category' not in ('practice','reading','continuity','reinforcement','thematic')
   or v_value->>'metric' not in ('questions','lessons','reviews','checkpoints','plan-steps','chapters','activity')
   or coalesce((v_value->>'target')::integer,0) not between 1 and 100 then raise exception 'Invalid assignment';end if;
 else
  if v_value->>'kind' not in ('mission_started','mission_progressed','mission_completed','mission_expired','mission_cancelled')
   or coalesce(v_value->>'missionId','')='' or coalesce((v_value->>'observedProgress')::integer,-1)<0 then raise exception 'Invalid lifecycle';end if;
 end if;
 insert into public.mission_events(event_id,user_id,device_id,platform,event_kind,payload)
 values(p_event_id::text,v_user,p_device_id,p_platform,v_kind,v_value) on conflict(user_id,event_id) do nothing returning mission_events.server_sequence into v_seq;
 if v_seq is null then select e.server_sequence into v_seq from public.mission_events e where e.user_id=v_user and e.event_id=p_event_id::text;return query select v_seq,false,coalesce((select s.total_xp from public.user_stats s where s.user_id=v_user),0);return;end if;
 return query select v_seq,true,coalesce((select s.total_xp from public.user_stats s where s.user_id=v_user),0);
end;$$;
revoke all on function public.submit_mission_event(uuid,uuid,text,jsonb) from public;
grant execute on function public.submit_mission_event(uuid,uuid,text,jsonb) to authenticated;
